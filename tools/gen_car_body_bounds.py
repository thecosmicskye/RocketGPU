#!/usr/bin/env python3

import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = [l.rstrip("\n").split("\t") for l in open(os.path.join(root, "tools/data/car_body_mesh_bounds.tsv")) if l[0] != "#"]
assert rows[0][0] == "body" and all(len(r) == 8 for r in rows)
rows = rows[1:]
f = lambda v: v + ("f" if "." in v else ".0f")
out = ["// Generated by tools/gen_car_body_bounds.py from tools/data/car_body_mesh_bounds.tsv. Do not edit.",
       "// X(name, centre x, y, z, half extent x, y, z): each car body's stored mesh bounds in uu, by CarConfig::body.",
       "#define ROCKETGPU_CAR_BODIES(X) \\"]
out += ["    X(\"%s\", %s) \\" % (r[0], ", ".join(f(v) for v in r[2:])) for r in rows]
out[-1] = out[-1][:-2]
open(os.path.join(root, "include/rocketgpu/detail/car_body_bounds.inc"), "w").write("\n".join(out) + "\n")
print("bodies", len(rows))
