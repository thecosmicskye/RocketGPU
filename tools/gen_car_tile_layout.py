import os, re, subprocess, sys, tempfile

GROUPS = [
    ("pose", "rot pos_bt basis_forward basis_right basis_up pos vel ang_vel vel_bt basis_authoritative is_demoed "
             "just_respawned is_on_ground ext_force_impulse_bt_valid restored_inv_inertia_valid vel_touched_solve_stage "
             "set_wheel_normals_mask wheels_with_contact handbrake_val"),
    ("contact", "world_contact ext_force_impulse_bt ext_torque_impulse solve_delta_linear_bt solve_delta_angular car_contact "
                "tick_count_since_update last_ball_started_with_world boost_pad_touching cal_pre_flags pending_bump_count"),
    ("ticks", "vel_impulse_cache vel_impulse_cache_bt last_ball_contact_start last_world_surface_contact "
              "first_world_after_last_ball last_flip_or_jump_start flip_or_jump_last_tick pad_frame_pos_valid"),
    ("game", "tick_start_pos_bt pad_frame_pos_bt cal_tick_start_ang_vel boost flip_time jump_time air_time air_time_since_jump "
             "supersonic_time auto_flip_timer internal_jump_time internal_flip_time cal_pre_pitchlock_restart_time "
             "cal_pre_forward_speed_uu boosting_time time_since_boosted driving_disabled ball_contact_last_tick "
             "ball_contact_this_tick has_jumped has_double_jumped has_flipped is_flipping is_jumping is_boosting is_supersonic "
             "is_auto_flipping demo_no_contact_response flip_timer_live internal_has_double_jumped reported_flags "
             "game_has_jumped double_jump_ticks supersonic_set_v3"),
    ("frame", "tick_start_basis_forward tick_start_basis_right tick_start_basis_up"),
]
WIDE = "last_controls ball_hit_info".split()
LANES, WORD = 32, 16
SCALAR = {"float": (4, 4), "uint8_t": (1, 1), "uint16_t": (2, 2), "uint32_t": (4, 4), "uint64_t": (8, 8), "int32_t": (4, 4),
          "Vec3": (12, 4), "Quat": (16, 4), "BallHitInfo": (64, 8), "CarControls": (24, 4)}

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with tempfile.NamedTemporaryFile("w", suffix=".cpp", delete=False) as tu:
    tu.write('#include "rocketgpu/rocketgpu.h"\nrocketgpu::CarState v;\n')
dump = subprocess.run([os.environ.get("CXX", "clang++"), "-std=c++17", "-I", os.path.join(root, "include"), "-fsyntax-only",
                       "-Xclang", "-fdump-record-layouts", tu.name], capture_output=True, text=True, check=True).stdout
os.unlink(tu.name)
lines = dump.splitlines()
start = next(i for i, l in enumerate(lines) if re.match(r"^\s*0 \| struct rocketgpu::CarState$", l))
fields = []
unnamed = {}
for l in lines[start + 1:]:
    if "[sizeof=" in l:
        car_size = int(re.search(r"sizeof=(\d+)", l).group(1))
        break
    m = re.match(r"^\s*(\d+) \|   (\S.*)$", l)
    if not m:
        continue
    off, decl = int(m.group(1)), m.group(2)
    name = decl.split()[-1]
    t = decl[: -len(name)].strip().replace("struct rocketgpu::", "").replace("rocketgpu::", "")
    arr = re.match(r"^(\w+)\[(\d+)\]$", t)
    if arr:
        s, a = SCALAR[arr.group(1)]
        fields.append([name, off, s * int(arr.group(2)), a])
    elif t in SCALAR:
        fields.append([name, off, *SCALAR[t]])
    else:
        fields.append([name, off, None, 4])
for i, f in enumerate(fields):
    if f[2] is None:
        f[2] = fields[i + 1][1] - f[1]
by = {f[0]: f for f in fields}

place = {}
words = []
for gname, names in GROUPS:
    names = names.split()
    assert all(n in by for n in names), [n for n in names if n not in by]
    big = [n for n in names if by[n][2] > 8]
    small = sorted([n for n in names if by[n][2] <= 8], key=lambda n: -by[n][2])
    gw = []
    for n in big:
        assert by[n][2] <= WORD, n
        words.append([by[n][2]]); gw.append(len(words) - 1); place[n] = (0, (len(words) - 1) * LANES * WORD)
    for n in small:
        s, a = by[n][2], by[n][3]
        for w in gw:
            o = (words[w][0] + a - 1) // a * a
            if o + s <= WORD:
                words[w][0] = o + s; place[n] = (0, w * LANES * WORD + o); break
        else:
            words.append([s]); gw.append(len(words) - 1); place[n] = (0, (len(words) - 1) * LANES * WORD)
o = 0
for n in WIDE:
    s, a = by[n][2], by[n][3]
    o = (o + a - 1) // a * a; place[n] = (1, o); o += s
wide_bytes = (o + 15) // 16 * 16
o = 0
for f in fields:
    if f[0] in place:
        continue
    o = (o + f[3] - 1) // f[3] * f[3]; place[f[0]] = (2, o); o += f[2]
cold_bytes = (o + 15) // 16 * 16
nwords = len(words)
tile_bytes = LANES * (nwords * WORD + wide_bytes + cold_bytes)

out = [f"// Generated by tools/gen_car_tile_layout.py; do not edit.",
       f"// CUDA car tile: {LANES} car slots, {nwords} hot 16-byte words, a {wide_bytes}-byte wide record and a {cold_bytes}-byte cold",
       f"// record per lane ({tile_bytes} bytes per tile, {tile_bytes // LANES} per car; CarState is {car_size}).",
       f"#define ROCKETGPU_CAR_TILE_WORDS {nwords}",
       f"#define ROCKETGPU_CAR_TILE_WIDE_BYTES {wide_bytes}",
       f"#define ROCKETGPU_CAR_TILE_COLD_BYTES {cold_bytes}",
       f"#define ROCKETGPU_CAR_STATE_BYTES {car_size}",
       "// X(field, region, offset): region 0 = hot word (offset w * 512 + byte from the lane's word pointer),",
       "// 1 = wide record, 2 = cold record. CarState order.",
       "#define ROCKETGPU_CAR_TILE_FIELDS(X) \\"]
for f in fields:
    r, off = place[f[0]]
    out.append(f"    X({f[0]}, {r}, {off}) \\")
out.append("")
stretches, size = [[]], 0
for f in fields:
    if stretches[-1] and size + f[2] > 128:
        stretches.append([]); size = 0
    stretches[-1].append(f); size += f[2]
out.append("// The fields again in stretches of at most 128 CarState bytes: S(FIELDS) once per stretch, FIELDS(X) as above.")
for i, st in enumerate(stretches):
    out.append(f"#define ROCKETGPU_CAR_TILE_FIELDS_S{i}(X) \\")
    for f in st:
        r, off = place[f[0]]
        out.append(f"    X({f[0]}, {r}, {off}) \\")
    out.append("")
out.append("#define ROCKETGPU_CAR_TILE_STRETCHES(S) \\")
for i in range(len(stretches)):
    out.append(f"    S(ROCKETGPU_CAR_TILE_FIELDS_S{i}) \\")
out.append("")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
for gname, names in GROUPS:
    ws = sorted({place[n][1] // (LANES * WORD) for n in names.split()})
    print(f"{gname}: words {ws[0]}..{ws[-1]}")
print(f"words {nwords}, wide {wide_bytes}, cold {cold_bytes}, per car {tile_bytes // LANES} (CarState {car_size})")
