import re, sys

RECORDS = ["Vec3", "Quat", "BallHitInfo", "CarControls", "CarState", "BallState", "CarConfig", "EnvState",
           "detail::WheelRuntimeState"]
SCALARS = {"float": "float", "double": "double", "uint8_t": "uint8", "int8_t": "int8", "uint16_t": "uint16",
           "int16_t": "int16", "uint32_t": "uint32", "int32_t": "int32", "int": "int32", "uint64_t": "uint64",
           "int64_t": "int64"}
line_re = re.compile(r"^\s*(\d+)(:\d+-\d+)? \|( *)(.*)$")

import os, subprocess, tempfile
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out_dir = sys.argv[1]
with tempfile.NamedTemporaryFile("w", suffix=".cpp", delete=False) as tu:
    tu.write('#include "rocketgpu/detail/step.hpp"\n' + "".join(f"rocketgpu::{r} v{i};\n" for i, r in enumerate(RECORDS)))
dump = subprocess.run([os.environ.get("CXX", "clang++"), "-std=c++17", "-I", os.path.join(root, "include"), "-fsyntax-only",
                       "-Xclang", "-fdump-record-layouts", tu.name], capture_output=True, text=True, check=True).stdout
os.unlink(tu.name)
lines = dump.splitlines()
blocks = {}
for i, l in enumerate(lines):
    m = re.match(r"^\s*0 \| (struct|class) rocketgpu::((?:detail::)?\w+)$", l)
    if m and m.group(2) in RECORDS and m.group(2) not in blocks:
        body = []
        for l2 in lines[i + 1:]:
            if "[sizeof=" in l2:
                size = int(re.search(r"sizeof=(\d+)", l2).group(1))
                break
            body.append(l2)
        blocks[m.group(2)] = (body, size)

out, checks, emitted = [], [], set()

def ispc_type(t, owner, name, sub):
    t = t.replace("const ", "")
    if t in SCALARS:
        return SCALARS[t]
    m = re.match(r"(?:struct rocketgpu::)?(\w+(?:::\w+)?)$", t)
    if m:
        n = m.group(1).replace("::", "_")
        if n not in emitted:
            emit(n, sub, None)
        return n
    if t.startswith("struct rocketgpu::") and "(unnamed" in t:
        n = owner + "_" + name
        emit(n, sub, None)
        return n
    raise SystemExit(f"unmapped type {t!r} in {owner}.{name}")

def members(body, depth):
    res, cur = [], None
    for l in body:
        m = line_re.match(l)
        if not m:
            continue
        if m.group(2):
            raise SystemExit("bitfield: " + l)
        d = (len(m.group(3)) - 1) // 2
        if d == depth:
            cur = [int(m.group(1)), m.group(4), []]
            res.append(cur)
        elif d > depth and cur is not None:
            cur[2].append(l)
    return res

def emit(name, body, size):
    emitted.add(name)
    depth = None
    for l in body:
        m = line_re.match(l)
        if m:
            d = (len(m.group(3)) - 1) // 2
            depth = d if depth is None else min(depth, d)
    fields = []
    for off, decl, sub in members(body, depth):
        decl = decl.strip()
        am = re.match(r"^(.*)\[(\d+)\] (\w+)$", decl)
        if am:
            t, n, fname = am.group(1), int(am.group(2)), am.group(3)
        else:
            t, fname = decl.rsplit(" ", 1); n = 0
        it = ispc_type(t, name, fname, sub)
        fields.append((it, fname, n, off))
    out.append(f"struct {name} {{")
    for it, fname, n, off in fields:
        out.append(f"    {it} {fname}{f'[{n}]' if n else ''};  // {off}")
    out.append("};")
    if size is not None:
        checks.append((name, fields, size))

for r in RECORDS:
    n = r.split("::")[-1]
    if n not in emitted:
        emit(n, *blocks[r])
        if r != n:
            checks[-1] = (n, checks[-1][1], checks[-1][2], r)

open(os.path.join(out_dir, "rg_types.isph"), "w").write("// generated by tools/gen_ispc_types.py from the clang record layouts; do not edit\n#pragma once\n" + "\n".join(out) + "\n")

chk = ["// generated by tools/gen_ispc_types.py; do not edit", "extern \"C\" void rg_ispc_layout(int32_t* out);",
       "// true when every ISPC struct member sits at the C++ offset", "inline bool RgIspcLayoutOk() {",
       "    int32_t got[4096]{}; rg_ispc_layout(got); int k = 0, bad = 0;"]
isp = ["// generated by tools/gen_ispc_types.py; do not edit", "export void rg_ispc_layout(uniform int32 out[]) {", "    uniform int k = 0;"]
for name, fields, size, *qual in checks:
    cname = "rocketgpu::" + (qual[0] if qual else name)
    isp.append(f"    {{ uniform {name} * uniform p = (uniform {name} * uniform)0; out[k++] = sizeof(uniform {name});")
    chk.append(f"    if (got[k++] != (int)sizeof({cname})) ++bad;")
    for it, fname, n, off in fields:
        isp.append(f"      out[k++] = (uniform int32)((uniform int8 * uniform)&p->{fname} - (uniform int8 * uniform)p);")
        chk.append(f"    if (got[k++] != (int)offsetof({cname}, {fname})) ++bad;")
    isp.append("    }")
isp.append("}")
chk += ["    return bad == 0;", "}"]
open(os.path.join(out_dir, "rg_layout_check.inc"), "w").write("\n".join(chk) + "\n")
open(os.path.join(out_dir, "rg_layout.isph"), "w").write("\n".join(isp) + "\n")

SCALAR_SIZES = {"float": 4, "double": 8, "uint8_t": 1, "int8_t": 1, "uint16_t": 2, "int16_t": 2, "uint32_t": 4,
                "int32_t": 4, "int": 4, "uint64_t": 8, "int64_t": 8}
all_blocks = {}
for i, l in enumerate(lines):
    m = re.match(r"^\s*0 \| (?:struct|class) rocketgpu::((?:detail::)?\w+)$", l)
    if m and m.group(1).split("::")[-1] not in all_blocks:
        body = []
        for l2 in lines[i + 1:]:
            if "[sizeof=" in l2:
                all_blocks[m.group(1).split("::")[-1]] = (body, int(re.search(r"sizeof=(\d+)", l2).group(1)))
                break
            body.append(l2)

def data_ranges(name):
    res = []
    for l in all_blocks[name][0]:
        m = line_re.match(l)
        if not m:
            continue
        off, decl = int(m.group(1)), m.group(4).strip()
        if decl.startswith("struct "):
            continue
        am = re.match(r"^(.*)\[(\d+)\] (\w+)$", decl)
        t, n = (am.group(1), int(am.group(2))) if am else (decl.rsplit(" ", 1)[0], 1)
        t = t.replace("const ", "").replace("struct rocketgpu::", "").split("::")[-1]
        if t in SCALAR_SIZES:
            res.append((off, SCALAR_SIZES[t] * n))
        else:
            stride = all_blocks[t][1]
            res += [(off + k * stride + o, s) for k in range(n) for o, s in data_ranges(t)]
    return res

dr = ["// generated by tools/gen_ispc_types.py; do not edit", "#pragma once", "#include <cstdint>", "#include <cstring>",
      "namespace rocketgpu::detail {", "struct StateDataRange { uint16_t off, len; };"]
for r in ["CarState", "BallState", "detail::WheelRuntimeState"]:
    n = r.split("::")[-1]
    merged = []
    for o, s in sorted(data_ranges(n)):
        if merged and o <= merged[-1][0] + merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], o + s - merged[-1][0])
        else:
            merged.append([o, s])
    dr.append(f"static_assert(sizeof(rocketgpu::{r}) == {all_blocks[n][1]}, \"run tools/gen_ispc_types.py\");")
    dr.append(f"inline constexpr StateDataRange k{n}Data[] = {{" + ", ".join(f"{{{o}, {s}}}" for o, s in merged) + "};")
dr += ["// a and b hold equal bytes in every range of r (padding ignored)",
       "template <int N> inline bool StateDataEqual(const void* a, const void* b, const StateDataRange (&r)[N]) {",
       "    for (const StateDataRange& x : r)",
       "        if (std::memcmp(static_cast<const char*>(a) + x.off, static_cast<const char*>(b) + x.off, x.len) != 0) return false;",
       "    return true;", "}", "}  // namespace rocketgpu::detail"]
open(os.path.join(root, "include", "rocketgpu", "detail", "step", "state_data_ranges.hpp"), "w").write("\n".join(dr) + "\n")
